def clean_text(text: str) -> str:
    """清洗文本：小写化、移除特殊字符、压缩空白。"""
    text = text.lower()
    text = re.sub(r"[^a-zA-Z0-9\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def tokenize(text: str) -> List[str]:
    """简单空格分词。"""
    return clean_text(text).split()


# ── 词汇表构建 ────────────────────────────────────────────
class Vocabulary:
    """词汇表，负责词到索引的映射。"""

    PAD_TOKEN = "<pad>"
    UNK_TOKEN = "<unk>"

    def __init__(self):
        self.word2idx: Dict[str, int] = {}
        self.idx2word: List[str] = []
        self._add_token(self.PAD_TOKEN)  # index 0
        self._add_token(self.UNK_TOKEN)  # index 1

    def _add_token(self, word: str) -> int:
        if word not in self.word2idx:
            self.word2idx[word] = len(self.idx2word)
            self.idx2word.append(word)
        return self.word2idx[word]

    def build_from_texts(self, texts: List[str], max_size: int = 10000, min_freq: int = 1):
        """从文本列表构建词汇表。"""
        counter = Counter()
        for text in texts:
            counter.update(tokenize(text))

        # 按词频排序，取前 max_size 个
        for word, freq in counter.most_common(max_size):
            if freq >= min_freq:
                self._add_token(word)

    def encode(self, text: str, max_length: int = 200) -> List[int]:
        """将文本编码为索引序列，并进行填充/截断。"""
        tokens = tokenize(text)
        indices = [self.word2idx.get(t, self.word2idx[self.UNK_TOKEN]) for t in tokens]
        # 截断
        indices = indices[:max_length]
        # 填充
        if len(indices) < max_length:
            indices += [self.word2idx[self.PAD_TOKEN]] * (max_length - len(indices))
        return indices

    def __len__(self) -> int:
        return len(self.idx2word)

    def save(self, path: str):
        """保存词汇表到 JSON。"""
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump({"idx2word": self.idx2word}, f, ensure_ascii=False)

    @classmethod
    def load(cls, path: str) -> "Vocabulary":
        """从 JSON 加载词汇表。"""
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        vocab = cls()
        vocab.idx2word = data["idx2word"]
        vocab.word2idx = {w: i for i, w in enumerate(vocab.idx2word)}
        return vocab


# ── 数据集类 ──────────────────────────────────────────────
class SentimentDataset(Dataset):
    """情感分析 PyTorch 数据集。"""

    def __init__(self, texts: List[str], labels: List[int], vocab: Vocabulary, max_length: int = 200):
        self.texts = texts
        self.labels = labels
        self.vocab = vocab
        self.max_length = max_length

    def __len__(self) -> int:
        return len(self.texts)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        text = self.texts[idx]
        label = self.labels[idx]
        encoded = self.vocab.encode(text, max_length=self.max_length)
        return torch.tensor(encoded, dtype=torch.long), torch.tensor(label, dtype=torch.long)


# ── 数据加载函数 ──────────────────────────────────────────
def load_builtin_data() -> Tuple[List[str], List[int]]:
    """加载内置数据集。

    Returns:
        (texts, labels) 元组，labels 中 0=负面，1=正面。
    """
    texts = _NEGATIVE_SAMPLES + _POSITIVE_SAMPLES
    labels = [0] * len(_NEGATIVE_SAMPLES) + [1] * len(_POSITIVE_SAMPLES)
    return texts, labels


def load_csv_data(csv_path: str, text_col: str = "text", label_col: str = "label") -> Tuple[List[str], List[int]]:
    """从 CSV 文件加载数据。

    CSV 需包含文本列和标签列（0=负面，1=正面）。
    """
    import csv
    texts, labels = [], []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            texts.append(row[text_col])
            labels.append(int(row[label_col]))
    return texts, labels


def split_data(texts: List[str], labels: List[int], train_ratio: float = 0.8, seed: int = 42) -> Tuple:
    """打乱并划分训练集/测试集。

    Returns:
        (train_texts, train_labels, test_texts, test_labels)
    """
    import random
    random.seed(seed)
    combined = list(zip(texts, labels))
    random.shuffle(combined)
    texts, labels = zip(*combined)
    texts, labels = list(texts), list(labels)

    split_idx = int(len(texts) * train_ratio)
    return (
        texts[:split_idx], labels[:split_idx],
        texts[split_idx:], labels[split_idx:],
    )


def create_dataloaders(
    batch_size: int = 64,
    max_length: int = 200,
    max_vocab_size: int = 10000,
    csv_path: Optional[str] = None,
) -> Tuple[DataLoader, DataLoader, Vocabulary]:
    """创建训练和测试 DataLoader。

    Args:
        batch_size: 批次大小。
        max_length: 句子最大长度。
        max_vocab_size: 词汇表最大大小。
        csv_path: 可选的外部 CSV 数据路径，不填则使用内置数据。

    Returns:
        (train_loader, test_loader, vocab)
    """
    # 加载数据
    if csv_path and os.path.exists(csv_path):
        texts, labels = load_csv_data(csv_path)
        print(f"从 CSV 加载数据: {len(texts)} 条")
    else:
        texts, labels = load_builtin_data()
        print(f"使用内置数据集: {len(texts)} 条 (正面 {sum(labels)}, 负面 {len(labels)-sum(labels)})")

    # 划分数据集
    train_texts, train_labels, test_texts, test_labels = split_data(texts, labels)
    print(f"训练集: {len(train_texts)} 条, 测试集: {len(test_texts)} 条")

    # 构建词汇表（仅用训练集）
    vocab = Vocabulary()
    vocab.build_from_texts(train_texts, max_size=max_vocab_size)
    print(f"词汇表大小: {len(vocab)}")

    # 创建数据集
    train_dataset = SentimentDataset(train_texts, train_labels, vocab, max_length)
    test_dataset = SentimentDataset(test_texts, test_labels, vocab, max_length)

    # 创建 DataLoader
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

    return train_loader, test_loader, vocab
