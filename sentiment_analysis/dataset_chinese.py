# ── 中文文本预处理 ────────────────────────────────────────
def clean_chinese_text(text: str) -> str:
    """清洗中文文本：移除多余空白和特殊字符。"""
    # 移除多余空白
    text = re.sub(r"\s+", "", text)
    return text.strip()


def tokenize_chinese(text: str) -> List[str]:
    """中文分词：字符级分词，连续英文/数字作为一个 token。

    例如："这个手机很好用iPhone13" ->
    ['这', '个', '手', '机', '很', '好', '用', 'iPhone', '13']
    """
    text = clean_chinese_text(text)
    tokens = []
    # 匹配连续的英文单词或数字
    pattern = re.compile(r"[a-zA-Z]+|\d+|[\u4e00-\u9fff]|[^\s]")
    for match in pattern.finditer(text):
        tokens.append(match.group())
    return tokens


# ── 中文词汇表 ────────────────────────────────────────────
class ChineseVocabulary:
    """中文词汇表，字符级分词。"""

    PAD_TOKEN = "<pad>"
    UNK_TOKEN = "<unk>"

    def __init__(self):
        self.char2idx: Dict[str, int] = {}
        self.idx2char: List[str] = []
        self._add_token(self.PAD_TOKEN)
        self._add_token(self.UNK_TOKEN)

    def _add_token(self, char: str) -> int:
        if char not in self.char2idx:
            self.char2idx[char] = len(self.idx2char)
            self.idx2char.append(char)
        return self.char2idx[char]

    def build_from_texts(self, texts: List[str], max_size: int = 3000, min_freq: int = 1):
        """从文本列表构建词汇表。"""
        counter = Counter()
        for text in texts:
            counter.update(tokenize_chinese(text))
        for char, freq in counter.most_common(max_size):
            if freq >= min_freq:
                self._add_token(char)

    def encode(self, text: str, max_length: int = 150) -> List[int]:
        """将文本编码为索引序列，填充/截断到 max_length。"""
        tokens = tokenize_chinese(text)
        indices = [self.char2idx.get(t, self.char2idx[self.UNK_TOKEN]) for t in tokens]
        indices = indices[:max_length]
        if len(indices) < max_length:
            indices += [self.char2idx[self.PAD_TOKEN]] * (max_length - len(indices))
        return indices

    def __len__(self) -> int:
        return len(self.idx2char)

    def save(self, path: str):
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump({"idx2char": self.idx2char}, f, ensure_ascii=False)

    @classmethod
    def load(cls, path: str) -> "ChineseVocabulary":
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        vocab = cls()
        vocab.idx2char = data["idx2char"]
        vocab.char2idx = {c: i for i, c in enumerate(vocab.idx2char)}
        return vocab


# ── 中文数据集 ────────────────────────────────────────────
class ChineseSentimentDataset(Dataset):
    """中文情感分析数据集。"""

    def __init__(self, texts: List[str], labels: List[int], vocab: ChineseVocabulary, max_length: int = 150):
        self.texts = texts
        self.labels = labels
        self.vocab = vocab
        self.max_length = max_length

    def __len__(self) -> int:
        return len(self.texts)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        encoded = self.vocab.encode(self.texts[idx], max_length=self.max_length)
        return torch.tensor(encoded, dtype=torch.long), torch.tensor(self.labels[idx], dtype=torch.long)


# ── 数据加载函数 ──────────────────────────────────────────
def load_chinese_data() -> Tuple[List[str], List[int]]:
    """加载内置中文数据集。"""
    texts = _CHINESE_NEGATIVE + _CHINESE_POSITIVE
    labels = [0] * len(_CHINESE_NEGATIVE) + [1] * len(_CHINESE_POSITIVE)
    return texts, labels


def split_data(texts: List[str], labels: List[int], train_ratio: float = 0.8, seed: int = 42) -> Tuple:
    """打乱并划分训练/测试集。"""
    import random
    random.seed(seed)
    combined = list(zip(texts, labels))
    random.shuffle(combined)
    texts, labels = zip(*combined)
    texts, labels = list(texts), list(labels)
    split_idx = int(len(texts) * train_ratio)
    return (
        texts[:split_idx], labels[:split_idx],
        texts[split_idx:], labels[split_idx:],
    )


def create_chinese_dataloaders(
    batch_size: int = 32,
    max_length: int = 150,
    max_vocab_size: int = 3000,
) -> Tuple[DataLoader, DataLoader, ChineseVocabulary]:
    """创建中文情感分析 DataLoader。"""
    texts, labels = load_chinese_data()
    print(f"中文数据集: {len(texts)} 条 (正面 {sum(labels)}, 负面 {len(labels)-sum(labels)})")

    train_texts, train_labels, test_texts, test_labels = split_data(texts, labels)
    print(f"训练集: {len(train_texts)} 条, 测试集: {len(test_texts)} 条")

    vocab = ChineseVocabulary()
    vocab.build_from_texts(train_texts, max_size=max_vocab_size)
    print(f"中文字汇表大小: {len(vocab)}")

    train_dataset = ChineseSentimentDataset(train_texts, train_labels, vocab, max_length)
    test_dataset = ChineseSentimentDataset(test_texts, test_labels, vocab, max_length)

    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

    return train_loader, test_loader, vocab
